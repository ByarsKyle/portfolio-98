export const paint = {
  title: 'untitled - Paint',
  icon: 'paint',
  w: 400, h: 300,
  single: true,

  create(arg, api) {
    const buf = document.createElement('canvas');
    buf.width = 320; buf.height = 200;
    const bctx = buf.getContext('2d');
    bctx.fillStyle = '#ffffff';
    bctx.fillRect(0, 0, buf.width, buf.height);

    const PALETTE = [
      '#000000', '#808080', '#800000', '#808000', '#008000', '#008080', '#000080', '#800080',
      '#808040', '#004040', '#0080ff', '#004080', '#8000ff', '#804000',
      '#ffffff', '#c0c0c0', '#ff0000', '#ffff00', '#00ff00', '#00ffff', '#0000ff', '#ff00ff',
      '#ffff80', '#00ff80', '#80ffff', '#8080ff', '#ff0080', '#ff8040',
    ];
    const TOOLS = ['pencil', 'brush', 'eraser', 'fill', 'line', 'rect', 'ellipse', 'spray'];

    const st = {
      tool: 'brush', color: '#000000', color2: '#ffffff',
      drawing: false, last: null, start: null, size: 2,
    };

    function toBuf(ax, ay, canvasRect) {
      return {
        x: Math.floor((ax - canvasRect.x) * (buf.width / canvasRect.w)),
        y: Math.floor((ay - canvasRect.y) * (buf.height / canvasRect.h)),
      };
    }

    function stroke(a, b) {
      bctx.strokeStyle = st.tool === 'eraser' ? '#ffffff' : st.color;
      bctx.lineWidth = st.tool === 'eraser' ? 12 : (st.tool === 'brush' ? 3 : 1.4);
      bctx.lineCap = 'round'; bctx.lineJoin = 'round';
      bctx.beginPath();
      bctx.moveTo(a.x, a.y); bctx.lineTo(b.x, b.y);
      bctx.stroke();
    }

    function floodFill(px, py, hex) {
      const img = bctx.getImageData(0, 0, buf.width, buf.height);
      const d = img.data;
      const idx = (x, y) => (y * buf.width + x) * 4;
      const target = [d[idx(px, py)], d[idx(px, py) + 1], d[idx(px, py) + 2]];
      const rgb = [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)];
      if (target[0] === rgb[0] && target[1] === rgb[1] && target[2] === rgb[2]) return;
      const stack = [[px, py]];
      const seen = new Uint8Array(buf.width * buf.height);
      while (stack.length) {
        const [x, y] = stack.pop();
        if (x < 0 || y < 0 || x >= buf.width || y >= buf.height) continue;
        const k = y * buf.width + x;
        if (seen[k]) continue;
        const i = k * 4;
        if (Math.abs(d[i] - target[0]) > 12 || Math.abs(d[i + 1] - target[1]) > 12 || Math.abs(d[i + 2] - target[2]) > 12) continue;
        seen[k] = 1;
        d[i] = rgb[0]; d[i + 1] = rgb[1]; d[i + 2] = rgb[2];
        stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
      }
      bctx.putImageData(img, 0, 0);
    }

    const app = {
      title: 'untitled - Paint', icon: 'paint',
      w: 400, h: 300, minW: 300, minH: 220,
      menus: [
        { label: 'File', items: [{ label: 'New', id: 'new' }, { label: 'Save', id: 'save' }, '-', { label: 'Exit', id: 'exit' }] },
        { label: 'Edit', items: [{ label: 'Undo', disabled: true }, { label: 'Clear Image', id: 'new' }] },
        { label: 'Image', items: [{ label: 'Flip/Rotate', id: 'flip' }, { label: 'Invert Colors', id: 'invert' }] },
        { label: 'Help', items: [{ label: 'About Paint', id: 'about' }] },
      ],
      command(id, win, papi) {
        if (id === 'exit' || id === 'Exit') papi.close(win);
        else if (id === 'new' || id === 'New' || id === 'Clear Image') {
          bctx.fillStyle = '#ffffff'; bctx.fillRect(0, 0, buf.width, buf.height);
        } else if (id === 'save' || id === 'Save') {
          papi.messageBox('Paint', 'Cannot save to A:\\\n\nInsert a disk and try again.', { icon: 'error', w: 280 });
        } else if (id === 'invert' || id === 'Invert Colors') {
          const img = bctx.getImageData(0, 0, buf.width, buf.height);
          const d = img.data;
          for (let i = 0; i < d.length; i += 4) { d[i] = 255 - d[i]; d[i + 1] = 255 - d[i + 1]; d[i + 2] = 255 - d[i + 2]; }
          bctx.putImageData(img, 0, 0);
        } else if (id === 'flip' || id === 'Flip/Rotate') {
          const tmp = document.createElement('canvas');
          tmp.width = buf.width; tmp.height = buf.height;
          tmp.getContext('2d').drawImage(buf, 0, 0);
          bctx.save(); bctx.scale(-1, 1); bctx.drawImage(tmp, -buf.width, 0); bctx.restore();
        } else if (id === 'about' || id === 'About Paint') {
          papi.messageBox('About Paint', 'Microsoft Paint\n\nStill the fastest way to crop a\nscreenshot, twenty-five years later.', { icon: 'paint', w: 300 });
        }
      },
      draw(ctx, r, win) {
        fill(ctx, r.x, r.y, r.w, r.h, C.face);

        // tool box
        const tbW = 34;
        st.toolRects = [];
        TOOLS.forEach((t, i) => {
          const bx = r.x + 2 + (i % 2) * 16;
          const by = r.y + 2 + Math.floor(i / 2) * 16;
          button(ctx, bx, by, 16, 16, null, { pressed: st.tool === t });
          drawTool(ctx, t, bx + 8, by + 8, st.tool === t);
          st.toolRects.push({ x: bx, y: by, w: 16, h: 16, tool: t });
        });

        // canvas area
        const cw = r.w - tbW - 8, ch = r.h - 46;
        const cx = r.x + tbW + 4, cy = r.y + 2;
        fill(ctx, cx, cy, cw, ch, '#808080');
        const scale = Math.min(cw / buf.width, ch / buf.height, 1.4);
        const dw = Math.floor(buf.width * scale), dh = Math.floor(buf.height * scale);
        const dx = cx + 4, dy = cy + 4;
        bevelIn(ctx, dx - 2, dy - 2, dw + 4, dh + 4);
        ctx.imageSmoothingEnabled = false;
        ctx.drawImage(buf, dx, dy, dw, dh);
        st.canvasRect = { x: dx, y: dy, w: dw, h: dh };

        // preview of the in-progress shape
        if (st.drawing && st.start && st.preview && ['line', 'rect', 'ellipse'].includes(st.tool)) {
          ctx.save();
          ctx.strokeStyle = st.color; ctx.lineWidth = 1;
          const sx = dx + st.start.x * scale, sy = dy + st.start.y * scale;
          const ex = dx + st.preview.x * scale, ey = dy + st.preview.y * scale;
          ctx.beginPath();
          if (st.tool === 'line') { ctx.moveTo(sx, sy); ctx.lineTo(ex, ey); }
          else if (st.tool === 'rect') ctx.rect(sx, sy, ex - sx, ey - sy);
          else ctx.ellipse((sx + ex) / 2, (sy + ey) / 2, Math.abs(ex - sx) / 2, Math.abs(ey - sy) / 2, 0, 0, Math.PI * 2);
          ctx.stroke();
          ctx.restore();
        }

        // palette
        const py = r.y + r.h - 34;
        fill(ctx, r.x + 2, py, r.w - 4, 32, C.face);
        // current colours
        bevelIn(ctx, r.x + 4, py + 4, 26, 24);
        fill(ctx, r.x + 16, py + 14, 12, 12, st.color2);
        ctx.strokeStyle = '#000'; ctx.strokeRect(r.x + 16.5, py + 14.5, 11, 11);
        fill(ctx, r.x + 8, py + 8, 12, 12, st.color);
        ctx.strokeRect(r.x + 8.5, py + 8.5, 11, 11);

        st.palRects = [];
        PALETTE.forEach((col, i) => {
          const px = r.x + 36 + (i % 14) * 15;
          const pyy = py + 4 + Math.floor(i / 14) * 13;
          fill(ctx, px, pyy, 13, 11, col);
          bevelIn(ctx, px, pyy, 13, 11, 1);
          st.palRects.push({ x: px, y: pyy, w: 13, h: 11, color: col });
        });
      },
      mouse(type, x, y, btn, win, papi) {
        const b = win.maximized ? { x: 0, y: 0 } : { x: win.x, y: win.y };
        const ax = x + b.x + 3, ay = y + b.y + 40;

        if (type === 'down') {
          for (const t of st.toolRects ?? []) {
            if (ax >= t.x && ax <= t.x + t.w && ay >= t.y && ay <= t.y + t.h) {
              st.tool = t.tool; papi.sound('click'); return;
            }
          }
          for (const p of st.palRects ?? []) {
            if (ax >= p.x && ax <= p.x + p.w && ay >= p.y && ay <= p.y + p.h) {
              if (btn === 2) st.color2 = p.color; else st.color = p.color;
              papi.sound('click'); return;
            }
          }
        }

        const cr = st.canvasRect;
        if (!cr) return;
        const inside = ax >= cr.x && ax <= cr.x + cr.w && ay >= cr.y && ay <= cr.y + cr.h;
        const p = toBuf(ax, ay, cr);

        if (type === 'down' && inside) {
          st.drawing = true;
          st.start = p; st.last = p; st.preview = p;
          if (st.tool === 'fill') { floodFill(p.x, p.y, btn === 2 ? st.color2 : st.color); st.drawing = false; }
          else if (st.tool === 'pencil' || st.tool === 'brush' || st.tool === 'eraser') stroke(p, p);
          else if (st.tool === 'spray') spray(p);
        } else if (type === 'move' && st.drawing) {
          st.preview = p;
          if (st.tool === 'pencil' || st.tool === 'brush' || st.tool === 'eraser') { stroke(st.last, p); st.last = p; }
          else if (st.tool === 'spray') spray(p);
        } else if (type === 'up' && st.drawing) {
          if (['line', 'rect', 'ellipse'].includes(st.tool) && st.start) {
            bctx.strokeStyle = st.color; bctx.lineWidth = 1.4;
            bctx.beginPath();
            if (st.tool === 'line') { bctx.moveTo(st.start.x, st.start.y); bctx.lineTo(p.x, p.y); }
            else if (st.tool === 'rect') bctx.rect(st.start.x, st.start.y, p.x - st.start.x, p.y - st.start.y);
            else bctx.ellipse((st.start.x + p.x) / 2, (st.start.y + p.y) / 2,
              Math.abs(p.x - st.start.x) / 2, Math.abs(p.y - st.start.y) / 2, 0, 0, Math.PI * 2);
            bctx.stroke();
          }
          st.drawing = false; st.start = null;
        }
      },
    };

    function spray(p) {
      bctx.fillStyle = st.color;
      for (let i = 0; i < 12; i++) {
        const a = Math.random() * Math.PI * 2, rr = Math.random() * 7;
        bctx.fillRect(p.x + Math.cos(a) * rr, p.y + Math.sin(a) * rr, 1, 1);
      }
    }

    function drawTool(ctx, t, cx, cy, on) {
      const o = on ? 1 : 0;
      ctx.save();
      ctx.translate(cx + o, cy + o);
      ctx.strokeStyle = '#000'; ctx.fillStyle = '#000'; ctx.lineWidth = 1;
      if (t === 'pencil') { ctx.beginPath(); ctx.moveTo(-4, 4); ctx.lineTo(3, -3); ctx.stroke(); ctx.fillRect(-5, 3, 2, 2); }
      else if (t === 'brush') { ctx.beginPath(); ctx.moveTo(-4, 4); ctx.lineTo(2, -2); ctx.lineWidth = 2.4; ctx.stroke(); ctx.beginPath(); ctx.arc(3, -3, 2, 0, Math.PI * 2); ctx.fill(); }
      else if (t === 'eraser') { ctx.fillStyle = '#fff'; ctx.fillRect(-4, -2, 8, 6); ctx.strokeRect(-4.5, -2.5, 9, 7); }
      else if (t === 'fill') { ctx.beginPath(); ctx.moveTo(-4, 0); ctx.lineTo(0, -4); ctx.lineTo(4, 0); ctx.lineTo(0, 4); ctx.closePath(); ctx.stroke(); ctx.fillRect(2, 2, 3, 4); }
      else if (t === 'line') { ctx.beginPath(); ctx.moveTo(-4, 4); ctx.lineTo(4, -4); ctx.stroke(); }
      else if (t === 'rect') ctx.strokeRect(-4.5, -3.5, 9, 7);
      else if (t === 'ellipse') { ctx.beginPath(); ctx.ellipse(0, 0, 4.5, 3.5, 0, 0, Math.PI * 2); ctx.stroke(); }
      else if (t === 'spray') { for (let i = 0; i < 9; i++) ctx.fillRect(-4 + (i * 7 % 9), -4 + (i * 5 % 9), 1, 1); }
      ctx.restore();
    }

    return app;
  },
};

