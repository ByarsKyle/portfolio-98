export const notepad = {
  title: 'Notepad',
  icon: 'notepad',
  w: 400, h: 300,

  create(arg, api) {
    const file = FILES[arg] ?? FILES.empty;
    const st = {
      lines: file.body.split('\n'),
      name: file.name,
      cursor: { line: 0, col: 0 },
      scroll: 0,
      blink: 0,
      wrap: false,
      dirty: false,
    };

    const LH = 13;

    const app = {
      title: `${file.name} - Notepad`,
      icon: 'notepad',
      w: 420, h: 300,
      minW: 220, minH: 140,
      menus: [
        { label: 'File', items: [
          { label: 'New', id: 'new' }, { label: 'Open...', id: 'open' },
          { label: 'Save', id: 'save', accel: 'Ctrl+S' }, { label: 'Save As...', id: 'saveas' },
          '-', { label: 'Print', id: 'print' }, '-', { label: 'Exit', id: 'exit' },
        ] },
        { label: 'Edit', items: [
          { label: 'Undo', disabled: true, accel: 'Ctrl+Z' }, '-',
          { label: 'Cut', accel: 'Ctrl+X', disabled: true },
          { label: 'Copy', accel: 'Ctrl+C', disabled: true },
          { label: 'Paste', accel: 'Ctrl+V', disabled: true },
          '-', { label: 'Select All', id: 'selectall', accel: 'Ctrl+A' },
          { label: 'Time/Date', id: 'timedate', accel: 'F5' },
        ] },
        { label: 'Search', items: [{ label: 'Find...', id: 'find', accel: 'Ctrl+F' }, { label: 'Find Next', disabled: true }] },
        { label: 'Help', items: [{ label: 'Help Topics', id: 'help' }, '-', { label: 'About Notepad', id: 'about' }] },
      ],

      command(id, win, papi) {
        if (id === 'exit' || id === 'Exit') papi.close(win);
        else if (id === 'new' || id === 'New') { st.lines = ['']; st.name = 'Untitled'; win.title = 'Untitled - Notepad'; st.cursor = { line: 0, col: 0 }; }
        else if (id === 'save' || id === 'Save' || id === 'saveas') {
          papi.messageBox('Notepad', 'Cannot create the file.\n\nThe disk is write-protected,\nor imaginary.', { icon: 'error', w: 290 });
        } else if (id === 'open' || id === 'Open...') {
          papi.messageBox('Open', 'This dialog is not implemented.\n\nTry the Documents folder in the\nStart menu instead.', { icon: 'info', w: 300 });
        } else if (id === 'print' || id === 'Print') {
          papi.messageBox('Notepad', 'There is no printer attached.\n\nThere was never a printer attached.', { icon: 'warn', w: 300 });
        } else if (id === 'timedate' || id === 'Time/Date') {
          const d = new Date();
          const s = `${d.toLocaleTimeString()} ${d.toLocaleDateString()}`;
          insert(s);
        } else if (id === 'about' || id === 'About Notepad') {
          papi.messageBox('About Notepad', 'Notepad\nMicrosoft (R) Windows (R) 98\n\nIt opens text. That is the whole product.', { icon: 'notepad', w: 300 });
        } else if (id === 'help' || id === 'Help Topics') {
          papi.messageBox('Windows Help', 'Help is not available for this topic.\n\nIt was 1998. Nobody read it anyway.', { icon: 'help', w: 300 });
        }
      },

      key(e, win, papi) {
        const c = st.cursor;
        const line = st.lines[c.line] ?? '';
        st.blink = 0;
        if (e.ctrlKey) {
          if (e.key === 's') { app.command('save', win, papi); }
          return;
        }
        switch (e.key) {
          case 'ArrowLeft':
            if (c.col > 0) c.col--;
            else if (c.line > 0) { c.line--; c.col = st.lines[c.line].length; }
            break;
          case 'ArrowRight':
            if (c.col < line.length) c.col++;
            else if (c.line < st.lines.length - 1) { c.line++; c.col = 0; }
            break;
          case 'ArrowUp':
            if (c.line > 0) { c.line--; c.col = Math.min(c.col, st.lines[c.line].length); }
            break;
          case 'ArrowDown':
            if (c.line < st.lines.length - 1) { c.line++; c.col = Math.min(c.col, st.lines[c.line].length); }
            break;
          case 'Home': c.col = 0; break;
          case 'End': c.col = line.length; break;
          case 'PageUp': c.line = Math.max(0, c.line - 12); c.col = Math.min(c.col, st.lines[c.line].length); break;
          case 'PageDown': c.line = Math.min(st.lines.length - 1, c.line + 12); c.col = Math.min(c.col, st.lines[c.line].length); break;
          case 'Backspace':
            if (c.col > 0) {
              st.lines[c.line] = line.slice(0, c.col - 1) + line.slice(c.col);
              c.col--;
            } else if (c.line > 0) {
              const prev = st.lines[c.line - 1];
              st.lines[c.line - 1] = prev + line;
              st.lines.splice(c.line, 1);
              c.line--; c.col = prev.length;
            }
            st.dirty = true;
            break;
          case 'Delete':
            if (c.col < line.length) st.lines[c.line] = line.slice(0, c.col) + line.slice(c.col + 1);
            else if (c.line < st.lines.length - 1) {
              st.lines[c.line] = line + st.lines[c.line + 1];
              st.lines.splice(c.line + 1, 1);
            }
            st.dirty = true;
            break;
          case 'Enter':
            st.lines.splice(c.line + 1, 0, line.slice(c.col));
            st.lines[c.line] = line.slice(0, c.col);
            c.line++; c.col = 0;
            st.dirty = true;
            break;
          case 'Tab': insert('    '); break;
          default:
            if (e.key.length === 1) insert(e.key);
        }
        // keep the caret on screen
        const visible = Math.floor((win.h - 60) / LH);
        if (c.line < st.scroll) st.scroll = c.line;
        if (c.line > st.scroll + visible - 1) st.scroll = c.line - visible + 1;
      },

      update(dt) { st.blink += dt; },

      draw(ctx, r, win) {
        fill(ctx, r.x, r.y, r.w, r.h, C.face);
        const SB = 15;
        const view = { x: r.x + 2, y: r.y + 2, w: r.w - 4 - SB, h: r.h - 4 - SB };
        fill(ctx, view.x, view.y, view.w + SB, view.h + SB, C.white);
        bevelIn(ctx, r.x, r.y, r.w, r.h);

        ctx.save();
        ctx.beginPath(); ctx.rect(view.x, view.y, view.w, view.h); ctx.clip();
        ctx.font = FONT.mono;
        const visible = Math.ceil(view.h / LH);
        for (let i = 0; i < visible; i++) {
          const li = st.scroll + i;
          if (li >= st.lines.length) break;
          text(ctx, st.lines[li], view.x + 3, view.y + 2 + i * LH, { font: FONT.mono, color: '#000' });
        }
        // caret
        if (Math.floor(st.blink * 2) % 2 === 0) {
          const cl = st.cursor.line - st.scroll;
          if (cl >= 0 && cl < visible) {
            const pre = (st.lines[st.cursor.line] ?? '').slice(0, st.cursor.col);
            const cx = view.x + 3 + ctx.measureText(pre).width;
            fill(ctx, cx, view.y + 2 + cl * LH, 1, LH - 1, '#000');
          }
        }
        ctx.restore();

        st.maxScroll = Math.max(0, st.lines.length - Math.floor(view.h / LH));
        st.view = view;
        scrollBar(ctx, r.x + r.w - SB - 2, r.y + 2, SB, r.h - 4 - SB, st.scroll, view.h / LH, st.lines.length, true);
        scrollBar(ctx, r.x + 2, r.y + r.h - SB - 2, r.w - 4 - SB, SB, 0, 1, 1, false);
      },

      mouse(type, x, y, btn, win, papi) {
        if (type !== 'down' && type !== 'dblclick') return;
        const view = st.view;
        if (!view) return;
        const b = win.maximized ? { x: 0, y: 0 } : { x: win.x, y: win.y };
        const ax = x + b.x + 3, ay = y + b.y + 40;
        // scroll wheel substitutes: clicking the bar
        if (ax > view.x + view.w) {
          if (ay < view.y + 15) st.scroll = Math.max(0, st.scroll - 3);
          else if (ay > view.y + view.h - 15) st.scroll = Math.min(st.maxScroll, st.scroll + 3);
          else st.scroll = Math.round(((ay - view.y - 15) / Math.max(1, view.h - 30)) * st.maxScroll);
          return;
        }
        if (ax >= view.x && ax <= view.x + view.w && ay >= view.y && ay <= view.y + view.h) {
          const li = Math.min(st.lines.length - 1, st.scroll + Math.floor((ay - view.y - 2) / LH));
          st.cursor.line = Math.max(0, li);
          // find the nearest column
          const lineStr = st.lines[st.cursor.line] ?? '';
          let best = 0, bestD = 1e9;
          for (let i = 0; i <= lineStr.length; i++) {
            const wpx = view.x + 3 + measure(lineStr.slice(0, i));
            const d = Math.abs(wpx - ax);
            if (d < bestD) { bestD = d; best = i; }
          }
          st.cursor.col = best;
          st.blink = 0;
        }
      },
    };

    let _ctx = null;
    function measure(s) {
      if (!_ctx) {
        const c = document.createElement('canvas');
        _ctx = c.getContext('2d');
      }
      _ctx.font = FONT.mono;
      return _ctx.measureText(s).width;
    }

    function insert(s) {
      const c = st.cursor;
      const line = st.lines[c.line] ?? '';
      st.lines[c.line] = line.slice(0, c.col) + s + line.slice(c.col);
      c.col += s.length;
      st.dirty = true;
    }

    return app;
  },
};

