export const media = {
  title: 'Media Player',
  icon: 'media',
  w: 268, h: 174,
  single: true,
  resizable: false,

  create(arg, api) {
    const TRACKS = [
      { name: 'CANYON.MID', len: 92 },
      { name: 'PASSPORT.MID', len: 64 },
      { name: 'CLOUDS.MID', len: 78 },
    ];
    const st = { track: 0, playing: false, pos: 0, bars: new Array(28).fill(0), t: 0 };

    const app = {
      title: 'Media Player', icon: 'media', w: 268, h: 178, resizable: false,
      menus: [
        { label: 'File', items: [{ label: 'Open...', id: 'open' }, '-', { label: 'Exit', id: 'exit' }] },
        { label: 'Device', items: TRACKS.map((t, i) => ({ label: t.name, id: `track:${i}` })) },
        { label: 'Help', items: [{ label: 'About Media Player', id: 'about' }] },
      ],
      command(id, win, papi) {
        if (id === 'exit' || id === 'Exit') papi.close(win);
        else if (id?.startsWith('track:')) { st.track = +id.split(':')[1]; st.pos = 0; }
        else if (id === 'open' || id === 'Open...') papi.messageBox('Media Player', 'No media devices found.\n\nCheck that your sound card is\ninstalled and that the IRQ is not 5.', { icon: 'warn', w: 300 });
        else if (id === 'about') papi.messageBox('About', 'Microsoft Media Player\nVersion 5.1\n\nPlays three MIDI files. Beautifully.', { icon: 'media', w: 280 });
        else {
          const i = TRACKS.findIndex((t) => t.name === id);
          if (i >= 0) { st.track = i; st.pos = 0; }
        }
      },
      update(dt, win, papi) {
        st.t += dt;
        if (st.playing) {
          st.pos += dt;
          if (st.pos >= TRACKS[st.track].len) { st.pos = 0; st.track = (st.track + 1) % TRACKS.length; }
        }
        for (let i = 0; i < st.bars.length; i++) {
          const target = st.playing
            ? Math.abs(Math.sin(st.t * (1.6 + i * 0.19) + i)) * (0.35 + 0.65 * Math.abs(Math.sin(st.t * 0.8 + i * 0.4)))
            : 0;
          st.bars[i] += (target - st.bars[i]) * Math.min(1, dt * (target > st.bars[i] ? 16 : 6));
        }
      },
      draw(ctx, r, win, papi) {
        fill(ctx, r.x, r.y, r.w, r.h, C.face);
        // visualiser
        const vx = r.x + 6, vy = r.y + 6, vw = r.w - 12, vh = 74;
        bevelIn(ctx, vx, vy, vw, vh);
        fill(ctx, vx + 2, vy + 2, vw - 4, vh - 4, '#08121c');
        const bw = (vw - 10) / st.bars.length;
        st.bars.forEach((b, i) => {
          const h = Math.max(1, b * (vh - 12));
          const bx = vx + 4 + i * bw;
          for (let yy = 0; yy < h; yy += 3) {
            const frac = yy / (vh - 12);
            ctx.fillStyle = frac > 0.72 ? '#ff4040' : frac > 0.45 ? '#ffd040' : '#40e070';
            ctx.fillRect(bx, vy + vh - 6 - yy, bw - 1.5, 2);
          }
        });
        // track name scrolls across the top of the display
        ctx.save();
        ctx.beginPath(); ctx.rect(vx + 2, vy + 2, vw - 4, 12); ctx.clip();
        const label = `${TRACKS[st.track].name}   ·   ${st.playing ? 'PLAYING' : 'STOPPED'}   ·   `;
        ctx.font = FONT.small;
        const tw = ctx.measureText(label).width;
        const off = st.playing ? (st.t * 26) % tw : 0;
        for (let i = 0; i < 3; i++) {
          text(ctx, label, vx + 4 - off + i * tw, vy + 8, { baseline: 'middle', font: FONT.small, color: '#50d0a0' });
        }
        ctx.restore();

        // seek bar
        const sy = vy + vh + 6;
        bevelIn(ctx, r.x + 6, sy, r.w - 12, 12);
        const frac = st.pos / TRACKS[st.track].len;
        fill(ctx, r.x + 8, sy + 2, (r.w - 16) * frac, 8, C.titleA2);
        const kx = r.x + 6 + (r.w - 12) * frac;
        button(ctx, kx - 3, sy - 2, 7, 16, null);
        st.seekRect = { x: r.x + 6, y: sy - 2, w: r.w - 12, h: 16 };

        // transport
        const by = sy + 22;
        const btns = [['play', '▶'], ['pause', '❚❚'], ['stop', '■'], ['prev', '|◀'], ['next', '▶|']];
        st.btnRects = [];
        btns.forEach(([id, glyph], i) => {
          const bx = r.x + 6 + i * 30;
          button(ctx, bx, by, 28, 22, null, { pressed: id === 'play' && st.playing });
          ctx.save();
          ctx.fillStyle = '#000';
          ctx.font = '10px Tahoma, sans-serif';
          ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
          ctx.fillText(glyph, bx + 14, by + 11);
          ctx.restore();
          st.btnRects.push({ x: bx, y: by, w: 28, h: 22, id });
        });
        // time
        const mm = Math.floor(st.pos / 60), ss = Math.floor(st.pos % 60);
        const tm = Math.floor(TRACKS[st.track].len / 60), ts = Math.floor(TRACKS[st.track].len % 60);
        bevelIn(ctx, r.x + r.w - 82, by, 76, 22);
        text(ctx, `${mm}:${String(ss).padStart(2, '0')} / ${tm}:${String(ts).padStart(2, '0')}`,
          r.x + r.w - 44, by + 11, { align: 'center', baseline: 'middle', font: FONT.small });
      },
      mouse(type, x, y, btn, win, papi) {
        if (type !== 'down') return;
        const b = win.maximized ? { x: 0, y: 0 } : { x: win.x, y: win.y };
        const ax = x + b.x + 3, ay = y + b.y + 40;
        for (const r of st.btnRects ?? []) {
          if (ax >= r.x && ax <= r.x + r.w && ay >= r.y && ay <= r.y + r.h) {
            papi.sound('click');
            if (r.id === 'play') { st.playing = true; papi.sound('music', { play: true, track: st.track }); }
            else if (r.id === 'pause') { st.playing = !st.playing; papi.sound('music', { play: st.playing, track: st.track }); }
            else if (r.id === 'stop') { st.playing = false; st.pos = 0; papi.sound('music', { play: false }); }
            else if (r.id === 'prev') { st.track = (st.track + TRACKS.length - 1) % TRACKS.length; st.pos = 0; if (st.playing) papi.sound('music', { play: true, track: st.track }); }
            else if (r.id === 'next') { st.track = (st.track + 1) % TRACKS.length; st.pos = 0; if (st.playing) papi.sound('music', { play: true, track: st.track }); }
            return;
          }
        }
        const sr = st.seekRect;
        if (sr && ax >= sr.x && ax <= sr.x + sr.w && ay >= sr.y && ay <= sr.y + sr.h) {
          st.pos = ((ax - sr.x) / sr.w) * TRACKS[st.track].len;
        }
      },
      dispose(win, papi) { papi.sound('music', { play: false }); },
    };
    return app;
  },
};

// ── MS-DOS Prompt ────────────────────────────────────────────
export const dos = {
  title: 'MS-DOS Prompt',
  icon: 'doc',
  w: 420, h: 268,
  single: true,

  create(arg, api) {
    const st = {
      lines: [
        'Microsoft(R) Windows 98',
        '   (C)Copyright Microsoft Corp 1981-1998.',
        '',
      ],
      input: '',
      cwd: 'C:\\WINDOWS',
      blink: 0,
      scroll: 0,
    };

    const FS = {
      'C:\\': ['WINDOWS <DIR>', 'PROGRAM~1 <DIR>', 'MYDOCU~1 <DIR>', 'AUTOEXEC.BAT', 'CONFIG.SYS', 'COMMAND.COM'],
      'C:\\WINDOWS': ['SYSTEM <DIR>', 'TEMP <DIR>', 'WIN.COM', 'NOTEPAD.EXE', 'WINMINE.EXE', 'SOL.EXE', 'CLOUD.BMP'],
      'C:\\MYDOCU~1': ['README.TXT', 'RESUME.TXT', 'TODO.TXT'],
    };

    function out(...ls) { st.lines.push(...ls); }

    function run(cmdline, papi) {
      const raw = cmdline.trim();
      const [cmd, ...args] = raw.split(/\s+/);
      const c = (cmd || '').toUpperCase();
      if (!c) return;
      switch (c) {
        case 'HELP':
          out('Available commands:', '',
            'CD       Changes the current directory.',
            'CLS      Clears the screen.',
            'DIR      Displays a list of files and subdirectories.',
            'ECHO     Displays messages.',
            'EXIT     Quits the MS-DOS Prompt.',
            'MEM      Displays the amount of used and free memory.',
            'TYPE     Displays the contents of a text file.',
            'VER      Displays the Windows version.',
            'WIN      Starts Windows.',
            '');
          break;
        case 'DIR': {
          const files = FS[st.cwd] ?? [];
          out(` Volume in drive C is MAIN`, ' Volume Serial Number is 1A2B-3C4D', ` Directory of ${st.cwd}`, '');
          for (const f of files) {
            const isDir = f.includes('<DIR>');
            const name = f.replace(' <DIR>', '');
            const [base, ext] = name.split('.');
            out(`${base.padEnd(8)} ${(ext ?? '').padEnd(3)} ${isDir ? '<DIR>' : String(1024 + base.length * 317).padStart(9)}  11-14-98  ${['9:41a', '2:07p', '11:23a'][base.length % 3]}`);
          }
          out('', `        ${files.length} file(s)      ${(files.length * 4096).toLocaleString()} bytes`,
            '                       2,147,483,648 bytes free', '');
          break;
        }
        case 'CD': {
          const target = (args[0] ?? '').toUpperCase();
          if (!target) { out(st.cwd, ''); break; }
          if (target === '..') { st.cwd = 'C:\\'; break; }
          if (target === '\\') { st.cwd = 'C:\\'; break; }
          const next = st.cwd === 'C:\\' ? `C:\\${target}` : `${st.cwd}\\${target}`;
          if (FS[next]) st.cwd = next;
          else out('Invalid directory', '');
          break;
        }
        case 'CLS': st.lines = []; break;
        case 'ECHO': out(args.join(' ') || 'ECHO is on.', ''); break;
        case 'VER': out('', 'Windows 98 [Version 4.10.1998]', ''); break;
        case 'MEM':
          out('', 'Memory Type        Total  =   Used  +   Free',
            '----------------  -------   -------   -------',
            'Conventional          640K       92K      548K',
            'Upper                 155K      155K        0K',
            'Extended (XMS)     130,432K   19,204K  111,228K',
            '----------------  -------   -------   -------',
            'Total memory       131,227K   19,451K  111,776K', '');
          break;
        case 'TYPE': {
          const f = (args[0] ?? '').toUpperCase();
          const key = { 'README.TXT': 'readme', 'RESUME.TXT': 'resume', 'TODO.TXT': 'todo' }[f];
          if (key) papi.open('notepad', key);
          else out(`File not found - ${f || ''}`, '');
          break;
        }
        case 'WIN': out('', 'Windows is already running.', ''); break;
        case 'EXIT': return 'exit';
        case 'DOOM': case 'DOOM.EXE':
          out('', 'Bad command or file name', '',
            "(You didn't install it. You never install it.)", '');
          break;
        case 'FORMAT':
          out('', 'WARNING: ALL DATA ON NON-REMOVABLE DISK', 'DRIVE C: WILL BE LOST!',
            'Proceed with Format (Y/N)? N', '', 'Good choice.', '');
          break;
        default:
          out(`Bad command or file name`, '');
      }
      return null;
    }

    const app = {
      title: 'MS-DOS Prompt', icon: 'doc', w: 424, h: 272, minW: 300, minH: 180,
      key(e, win, papi) {
        st.blink = 0;
        if (e.key === 'Enter') {
          out(`${st.cwd}>${st.input}`);
          const r = run(st.input, papi);
          st.input = '';
          if (r === 'exit') papi.close(win);
        } else if (e.key === 'Backspace') st.input = st.input.slice(0, -1);
        else if (e.key.length === 1) st.input += e.key;
        // trim scrollback
        if (st.lines.length > 400) st.lines = st.lines.slice(-400);
      },
      update(dt) { st.blink += dt; },
      draw(ctx, r, win) {
        fill(ctx, r.x, r.y, r.w, r.h, '#000000');
        ctx.font = '12px "Courier New", monospace';
        const LH = 13;
        const rows = Math.floor((r.h - 6) / LH);
        const all = [...st.lines, `${st.cwd}>${st.input}`];
        const start = Math.max(0, all.length - rows);
        for (let i = start; i < all.length; i++) {
          text(ctx, all[i], r.x + 4, r.y + 3 + (i - start) * LH, {
            font: '12px "Courier New", monospace', color: '#c8c8c8',
          });
        }
        if (Math.floor(st.blink * 2) % 2 === 0) {
          const lastY = r.y + 3 + (all.length - 1 - start) * LH;
          const w = ctx.measureText(`${st.cwd}>${st.input}`).width;
          fill(ctx, r.x + 4 + w, lastY, 7, 11, '#c8c8c8');
        }
      },
    };
    return app;
  },
};
